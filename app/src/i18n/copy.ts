export function t(
  language: Language,
  key: CopyKey,
  values: Record<string, string | number> = {},
): string {
  let text: string = copy[language][key] ?? copy.en[key];
  for (const [name, value] of Object.entries(values)) {
    text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}
